export const modifier = (score: number) => Math.floor((score - 10) / 2)
export const profBonus = (level: number) => Math.ceil(level / 4) + 1
export const signed = (n: number) => (n >= 0 ? `+${n}` : `${n}`)
/** Saving throw or skill bonus: the ability modifier, plus the proficiency bonus if proficient. */
export const proficientBonus = (score: number, proficient: boolean, level: number) =>
  modifier(score) + (proficient ? profBonus(level) : 0)
